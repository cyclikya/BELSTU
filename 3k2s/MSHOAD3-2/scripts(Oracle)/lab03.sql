--Задание 4: Перемещение подчиненной ветки
CREATE OR REPLACE PROCEDURE sp_MoveSubtree (
    p_source_id IN NUMBER,
    p_target_id IN NUMBER
) IS
BEGIN
    UPDATE Departments 
        SET parent_id = p_target_id
        WHERE department_id = p_source_id;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Перемещено');
END sp_MoveSubtree;
