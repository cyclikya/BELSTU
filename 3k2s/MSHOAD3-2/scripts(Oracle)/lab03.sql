-- Задание 2: Отображение всех подчиненных узлов
CREATE OR REPLACE PROCEDURE sp_ShowSubtree (
    p_parent_id IN NUMBER
) IS
BEGIN
    FOR rec IN (
        SELECT 
            department_name,
            LEVEL AS level_num
        FROM Departments
            START WITH department_id = p_parent_id
            CONNECT BY PRIOR department_id = parent_id
            ORDER BY LEVEL, department_name
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(
            RPAD(LPAD(' ', rec.level_num * 2) || rec.department_name, 30) || 
            ' | Уровень: ' || rec.level_num
        );
    END LOOP;
END sp_ShowSubtree;

EXEC sp_ShowSubtree(1);



-- Задание 3: Добавление подчиненного узла
CREATE OR REPLACE PROCEDURE sp_AddChildNode (
    p_parent_id IN NUMBER,
    p_department_name IN VARCHAR2
) IS
BEGIN
    INSERT INTO Departments (department_id, department_name, parent_id)
    VALUES (
        (SELECT NVL(MAX(department_id), 0) + 1 FROM Departments),
        p_department_name,
        p_parent_id
    );
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Добавлен: ' || p_department_name);
END sp_AddChildNode;

