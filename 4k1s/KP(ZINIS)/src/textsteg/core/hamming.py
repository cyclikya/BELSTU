"""Расширенный код Хэмминга (8,4) с минимальным расстоянием d_min = 4.

Код строится из классического кода Хэмминга (7,4) добавлением одного бита
общей проверки на чётность. Это увеличивает минимальное кодовое расстояние
с 3 до 4 и переводит код в режим SEC-DED (Single Error Correction,
Double Error Detection):

    исправляет  t = floor((d_min - 1) / 2) = 1 ошибку в блоке;
    обнаруживает 2 ошибки одновременно с исправлением одной,
                 так как d_min >= t + s + 1  ->  4 >= 1 + 2 + 1.

Выбор d_min = 4 вместо d_min = 3 принципиален для решаемой задачи.
Классический код (7,4) при двойной ошибке выполняет ложное исправление:
синдром указывает на третий, исправный бит, и декодер молча выдаёт неверные
данные. Расширенный код такую ситуацию распознаёт и помечает блок как
стёртый, что позволяет приложению честно сообщить пользователю о
невозможности восстановления вместо выдачи искажённого сообщения.

Систематическая форма кода: первые k = 4 бита кодового слова совпадают с
информационными, далее идут три проверочных бита и бит общей чётности.

    Кодовое слово:  [ d1 d2 d3 d4 | p1 p2 p3 | p0 ]
                      информационные  проверочные  общая чётность
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import Enum

import numpy as np

from .bits import Bits

#: Длина информационного блока.
K = 4
#: Длина кодового слова базового кода Хэмминга (7,4).
N_BASE = 7
#: Длина кодового слова расширенного кода (7,4) + бит общей чётности.
N = 8
#: Минимальное кодовое расстояние расширенного кода.
D_MIN = 4
#: Число исправляемых ошибок в блоке.
T = 1
#: Скорость кода R = k / n.
RATE = K / N

# Проверочная подматрица A (4x3). Строки соответствуют информационным
# битам, столбцы — проверочным. Набор взят из учебника Блейхута (раздел
# 3.4 «Коды Хэмминга», с. 71), где матрицы G и H кода (7,4) приведены в
# систематическом виде. Любой порядок столбцов, при котором все семь
# столбцов H различны и ненулевые, даёт код Хэмминга с теми же
# параметрами; книжный выбран для прямой сверки с источником.
_A = np.array(
    [
        [1, 1, 0],
        [1, 0, 1],
        [0, 1, 1],
        [1, 1, 1],
    ],
    dtype=np.uint8,
)

#: Порождающая матрица G = [I_k | A], размер 4x7.
G_BASE = np.hstack([np.eye(K, dtype=np.uint8), _A])

#: Проверочная матрица H = [A^T | I_(n-k)], размер 3x7.
H_BASE = np.hstack([_A.T, np.eye(N_BASE - K, dtype=np.uint8)])

# Таблица «синдром -> номер ошибочной позиции». Синдром одиночной ошибки в
# позиции j равен j-му столбцу матрицы H, поэтому таблица строится прямо
# по столбцам. Ненулевых синдромов ровно 7 — по числу позиций кодового
# слова базового кода.
_SYNDROME_TO_POSITION: dict[tuple[int, ...], int] = {
    tuple(int(v) for v in H_BASE[:, j]): j for j in range(N_BASE)
}


class BlockStatus(Enum):
    """Результат декодирования одного кодового слова."""

    #: Ошибок не обнаружено.
    OK = "ok"
    #: Обнаружена и исправлена одиночная ошибка.
    CORRECTED = "corrected"
    #: Обнаружена двойная ошибка, исправление невозможно — блок стёрт.
    ERASED = "erased"


@dataclass(frozen=True)
class DecodedBlock:
    """Декодированный информационный блок и сведения о его достоверности."""

    data: Bits
    status: BlockStatus

    @property
    def is_reliable(self) -> bool:
        """Можно ли доверять содержимому блока."""
        return self.status is not BlockStatus.ERASED


def encode_block(data: Bits) -> Bits:
    """Кодирует один информационный блок из k = 4 бит в кодовое слово n = 8.

    Проверочные биты вычисляются умножением вектора данных на порождающую
    матрицу по модулю 2, после чего добавляется бит общей чётности —
    сумма по модулю 2 всех семи предшествующих бит.
    """
    if len(data) != K:
        raise ValueError(f"информационный блок должен содержать {K} бит")

    vector = np.array(data, dtype=np.uint8)
    codeword = (vector @ G_BASE) % 2          # базовое кодовое слово (7 бит)
    overall_parity = int(codeword.sum() % 2)  # бит общей чётности
    return [int(b) for b in codeword] + [overall_parity]


def decode_block(received: Bits) -> DecodedBlock:
    """Декодирует принятое кодовое слово длиной n = 8 бит.

    Алгоритм синдромного декодирования в режиме SEC-DED:

    1. По первым семи битам вычисляется синдром s = H * r^T.
    2. По всем восьми битам вычисляется общая чётность p.
    3. Решение принимается по паре (s, p):

       s = 0, p = 0  — ошибок нет;
       s != 0, p = 1 — одиночная ошибка, позиция определяется по синдрому;
       s = 0, p = 1  — ошибка в самом бите общей чётности, данные целы;
       s != 0, p = 0 — двойная ошибка, исправление невозможно (стирание).

    Последний случай и есть то, ради чего выбран d_min = 4: код (7,4) в
    этой ситуации выполнил бы ложное исправление.
    """
    if len(received) != N:
        raise ValueError(f"кодовое слово должно содержать {N} бит")

    word = np.array(received, dtype=np.uint8)
    syndrome = tuple(int(v) for v in (H_BASE @ word[:N_BASE]) % 2)
    overall_parity = int(word.sum() % 2)

    corrected = word.copy()
    syndrome_is_zero = syndrome == (0,) * (N_BASE - K)

    if syndrome_is_zero and overall_parity == 0:
        status = BlockStatus.OK
    elif syndrome_is_zero and overall_parity == 1:
        # Синдром нулевой, но общая чётность нарушена: пострадал сам бит
        # чётности. Информационные биты при этом достоверны.
        status = BlockStatus.CORRECTED
    elif overall_parity == 1:
        # Нечётное число ошибок при ненулевом синдроме — считаем ошибку
        # одиночной и исправляем указанную синдромом позицию.
        position = _SYNDROME_TO_POSITION[syndrome]
        corrected[position] ^= 1
        status = BlockStatus.CORRECTED
    else:
        # Ненулевой синдром при чётной общей чётности — обнаружена двойная
        # ошибка. Исправить её код не в состоянии, блок помечается стёртым.
        status = BlockStatus.ERASED

    return DecodedBlock(data=[int(b) for b in corrected[:K]], status=status)


def encode(bits: Bits) -> Bits:
    """Кодирует битовую последовательность произвольной длины.

    Последовательность разбивается на блоки по k бит; неполный последний
    блок дополняется нулями. Дополнение безопасно, поскольку истинная длина
    сообщения хранится в заголовке (см. модуль framing).
    """
    payload = list(bits)
    if len(payload) % K:
        payload += [0] * (K - len(payload) % K)

    encoded: Bits = []
    for i in range(0, len(payload), K):
        encoded.extend(encode_block(payload[i:i + K]))
    return encoded


def decode(bits: Bits) -> tuple[Bits, list[BlockStatus]]:
    """Декодирует последовательность кодовых слов.

    Возвращает пару: восстановленные информационные биты и список статусов
    по одному на кодовое слово. Статусы нужны разделу экспериментальных
    исследований — по ним считаются доли исправленных и стёртых блоков.

    Неполное кодовое слово в конце последовательности (следствие потери
    части битов при повреждении контейнера) отбрасывается: восстановить
    его невозможно.
    """
    decoded: Bits = []
    statuses: list[BlockStatus] = []

    for i in range(0, len(bits) - N + 1, N):
        block = decode_block(bits[i:i + N])
        decoded.extend(block.data)
        statuses.append(block.status)

    return decoded, statuses
