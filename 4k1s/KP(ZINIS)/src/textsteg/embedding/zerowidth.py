"""Метод встраивания на основе символов нулевой ширины.

В Unicode предусмотрены служебные символы, не имеющие начертания: они
занимают нулевую ширину и не отображаются ни одним шрифтом. В русском
тексте эти символы не несут функциональной нагрузки, поэтому их вставка не
изменяет ни вид документа, ни его содержание.

Алфавит кодирования
-------------------
    U+200B  ZERO WIDTH SPACE       (ZWSP)  ->  00
    U+200C  ZERO WIDTH NON-JOINER  (ZWNJ)  ->  01
    U+200D  ZERO WIDTH JOINER      (ZWJ)   ->  10
    U+2060  WORD JOINER            (WJ)    ->  11

Четыре различимых состояния дают b = 2 бита на позицию, что вдвое превышает
вместимость метода вариантов пробельного символа.

Символ U+FEFF, визуально эквивалентный перечисленным, в алфавит не включён:
в начале файла он трактуется как маркер порядка байтов (BOM) и обрабатывается
особым образом.

Позиции встраивания
-------------------
Слотом служит промежуток перед каждым межсловным пробелом. Правило
вычисляется непосредственно по стеготексту, поэтому метод является слепым.

Модель ошибок
-------------
Метод нечувствителен ко всей группе воздействий, меняющих оформление:
смене шрифта, размера и цвета, изменению регистра, исправлению опечаток и
замене слов — символы нулевой ширины не имеют начертания и не связаны с
буквами. Удаление и вставка слов порождают соответственно ошибки удаления
и вставки, смещающие последовательность. Целенаправленная очистка текста от
непечатаемых символов и преобразование в форматы, не сохраняющие служебные
символы, уничтожают канал полностью.

Ограничение метода: незаметность обеспечивается для наблюдателя, но не для
автоматического анализатора — символы алфавита обнаруживаются простым
поиском по коду.
"""

from __future__ import annotations

from ..core.bits import Bits
from ..errors import CapacityError
from .base import Embedder

# Символы алфавита. Порядок значим: индекс символа равен значению пары бит.
ZWSP = "​"
ZWNJ = "‌"
ZWJ = "‍"
WJ = "⁠"

#: Алфавит кодирования; индекс задаёт двухбитовое значение.
ALPHABET: tuple[str, ...] = (ZWSP, ZWNJ, ZWJ, WJ)

#: Обратное соответствие «символ -> значение».
_SYMBOL_TO_VALUE: dict[str, int] = {sym: idx for idx, sym in enumerate(ALPHABET)}

#: Множество символов алфавита для быстрой проверки принадлежности.
_ALPHABET_SET = frozenset(ALPHABET)

#: Символ-разделитель, перед которым размещается позиция встраивания.
_SLOT_ANCHOR = " "

#: Таблица удаления символов алфавита из текста.
_STRIP_TABLE: dict[int, None] = {ord(sym): None for sym in ALPHABET}


def contains_foreign_symbols(text: str) -> bool:
    """Содержит ли текст символы алфавита метода.

    Позволяет предупредить пользователя, что выбранный контейнер уже содержит
    служебные символы нулевой ширины и они будут удалены перед встраиванием.
    """
    return any(char in _ALPHABET_SET for char in text)


def sanitize(text: str) -> str:
    """Удаляет из текста все символы алфавита метода.

    Операция обязательна перед встраиванием. Извлечение читает символы
    алфавита в порядке их следования и не располагает признаком, по которому
    можно отличить собственный символ от постороннего. Документ, ранее
    прошедший через другую систему обработки или содержащий служебные символы
    по иным причинам, внёс бы в поток лишние биты, сместив всю последующую
    последовательность.

    Видимая часть документа при удалении не изменяется: символы алфавита не
    имеют начертания.
    """
    return text.translate(_STRIP_TABLE)


class ZeroWidthEmbedder(Embedder):
    """Кодирование пары бит невидимым символом Unicode."""

    name = "zerowidth"
    bits_per_slot = 2

    def count_slots(self, container: str) -> int:
        """Позиция встраивания приходится на каждый межсловный пробел."""
        return container.count(_SLOT_ANCHOR)

    def embed(self, container: str, bits: Bits) -> str:
        """Размещает биты в контейнере по два на позицию.

        Контейнер предварительно очищается от символов алфавита (см.
        sanitize): посторонние служебные символы неотличимы от собственных и
        сместили бы извлекаемую последовательность.

        Последовательность нечётной длины дополняется одним нулевым битом:
        позиция всегда несёт ровно два бита. Дополнение безопасно, так как
        истинная длина сообщения хранится в заголовке.
        """
        cleaned = sanitize(container)

        payload = list(bits)
        if len(payload) % self.bits_per_slot:
            payload.append(0)

        capacity = self.capacity(cleaned)
        if len(payload) > capacity:
            raise CapacityError(
                f"требуется {len(payload)} бит, вместимость контейнера "
                f"{capacity} бит ({self.count_slots(cleaned)} позиций "
                f"по {self.bits_per_slot} бита)"
            )

        out: list[str] = []
        position = 0
        for char in cleaned:
            if char == _SLOT_ANCHOR and position < len(payload):
                value = (payload[position] << 1) | payload[position + 1]
                out.append(ALPHABET[value])
                position += self.bits_per_slot
            out.append(char)
        return "".join(out)

    def extract(self, stego: str) -> Bits:
        """Считывает биты в порядке следования символов алфавита в тексте.

        Позиции, оставшиеся незанятыми при встраивании, не содержат символов
        алфавита и потому не попадают в результат. Символы, утраченные при
        редактировании текста, порождают ошибки удаления — их обнаружение и
        компенсация возложены на слой синхронизации.
        """
        bits: Bits = []
        for char in stego:
            if char in _ALPHABET_SET:
                value = _SYMBOL_TO_VALUE[char]
                bits.append((value >> 1) & 1)
                bits.append(value & 1)
        return bits
