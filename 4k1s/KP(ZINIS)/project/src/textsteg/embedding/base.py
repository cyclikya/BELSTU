"""Общий интерфейс методов встраивания.

Метод встраивания — нижний слой стегосистемы: он определяет, какими
изменениями контейнера кодируются нули и единицы. Вышележащие слои
(помехоустойчивый код, перемежитель, кадрирование) работают только с
битовыми последовательностями и о контейнере ничего не знают.

Всякий метод обязан быть слепым (blind): извлечение выполняется по одному
лишь стеготексту, без доступа к исходному контейнеру. Это требование
вытекает из модели применения — получатель документа располагает только
самим документом, возможно уже отредактированным.

Метод задаётся тремя составляющими:

    1) правило выбора позиций встраивания (слотов) — вычисляется по тексту;
    2) ёмкость одной позиции b — сколько бит несёт слот;
    3) правило кодирования — соответствие «состояние слота <-> значение бит».

Вместимость контейнера определяется как C = N * b, где N — число слотов.

О совпадении позиций у отправителя и получателя
-----------------------------------------------
Правило выбора слотов детерминировано, поэтому на неизменённом стеготексте
получатель находит в точности те же позиции, что и отправитель. Однако
неизменность стеготекста как раз и не гарантирована: редактирование текста
добавляет и удаляет слова, а вместе с ними — позиции встраивания. Расхождение
позиций при этом неизбежно и является не дефектом метода встраивания, а тем
самым источником ошибок вставки и удаления, для компенсации которых
предназначены вышележащие слои — синхромаркеры, перемежение и
помехоустойчивый код.
"""

from __future__ import annotations

from abc import ABC, abstractmethod

from ..core.bits import Bits


class Embedder(ABC):
    """Базовый класс метода встраивания бит в текстовый контейнер."""

    #: Краткое имя метода; используется в интерфейсе и таблицах результатов.
    name: str = "base"

    #: Число бит, переносимых одной позицией встраивания.
    bits_per_slot: int = 1

    @abstractmethod
    def count_slots(self, container: str) -> int:
        """Число позиций встраивания в контейнере."""

    @abstractmethod
    def embed(self, container: str, bits: Bits) -> str:
        """Встраивает биты в контейнер и возвращает стеготекст.

        Возбуждает CapacityError, если вместимости контейнера недостаточно.
        Незанятые позиции остаются в исходном состоянии.
        """

    @abstractmethod
    def extract(self, stego: str) -> Bits:
        """Извлекает всю битовую последовательность из стеготекста."""

    def capacity(self, container: str) -> int:
        """Вместимость контейнера в битах: C = N * b."""
        return self.count_slots(container) * self.bits_per_slot

    def __repr__(self) -> str:
        return f"{type(self).__name__}(name={self.name!r})"
