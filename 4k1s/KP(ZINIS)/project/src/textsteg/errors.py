"""Иерархия исключений программного средства.

Все ошибки, которые может породить встраивание или извлечение, наследуются
от общего класса TextStegError. Это позволяет вызывающему коду — прежде
всего графическому интерфейсу — перехватывать их одним обработчиком, а не
перечислять несвязанные типы из разных модулей.

Каждое исключение дополнительно наследуется от подходящего встроенного
класса, чтобы сохранялось привычное поведение: ошибки значений остаются
подвидом ValueError, ошибки хода выполнения — подвидом RuntimeError.
"""

from __future__ import annotations


class TextStegError(Exception):
    """Базовый класс ошибок программного средства."""


class CapacityError(TextStegError, ValueError):
    """Сообщение не помещается в контейнер.

    Объём необходимой вместимости можно узнать заранее функцией
    core.pipeline.required_capacity и сравнить с Embedder.capacity.
    """


class MessageTooLongError(TextStegError, ValueError):
    """Длина сообщения превышает предельную для формата.

    Поле длины в заголовке занимает 16 бит, поэтому сообщение не может быть
    длиннее 65535 байт независимо от вместимости контейнера.
    """


class HeaderError(TextStegError, ValueError):
    """Заголовок не распознан или содержит недопустимые значения."""


class PipelineError(TextStegError, RuntimeError):
    """Недопустимые параметры конвейера."""
