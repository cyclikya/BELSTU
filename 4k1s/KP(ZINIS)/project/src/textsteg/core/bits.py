"""Преобразования между байтами и битовыми последовательностями.

Битовая последовательность во всём проекте представляется списком целых
чисел 0/1. Такое представление проигрывает по памяти упакованным массивам,
но существенно нагляднее при отладке кодера, перемежителя и декодера,
а объёмы данных здесь невелики — единицы килобит.

Всюду используется порядок «старший бит первым» (MSB first): бит с весом
2^7 байта идёт в последовательности первым. Порядок зафиксирован, поскольку
кодер и декодер должны трактовать поток одинаково.
"""

from __future__ import annotations

#: Тип битовой последовательности.
Bits = list[int]


def bytes_to_bits(data: bytes) -> Bits:
    r"""Разворачивает байты в биты, старший бит каждого байта идёт первым.

    >>> bytes_to_bits(b"\x01")
    [0, 0, 0, 0, 0, 0, 0, 1]
    """
    bits: Bits = []
    for byte in data:
        for shift in range(7, -1, -1):
            bits.append((byte >> shift) & 1)
    return bits


def bits_to_bytes(bits: Bits) -> bytes:
    r"""Собирает биты обратно в байты.

    Неполный последний байт дополняется нулями справа: после повреждения
    стеготекста длина извлечённой последовательности может не быть кратной
    восьми, и функция обязана отработать без исключения.

    >>> bits_to_bytes([0, 0, 0, 0, 0, 0, 0, 1])
    b'\x01'
    """
    padded = list(bits)
    if len(padded) % 8:
        padded += [0] * (8 - len(padded) % 8)

    out = bytearray()
    for i in range(0, len(padded), 8):
        value = 0
        for bit in padded[i:i + 8]:
            value = (value << 1) | (bit & 1)
        out.append(value)
    return bytes(out)


def int_to_bits(value: int, width: int) -> Bits:
    """Представляет целое число битовой последовательностью заданной длины.

    Используется при сборке заголовка, где каждое поле занимает строго
    отведённое число бит.

    >>> int_to_bits(5, 8)
    [0, 0, 0, 0, 0, 1, 0, 1]
    """
    if value < 0 or value >= (1 << width):
        raise ValueError(f"значение {value} не помещается в {width} бит")
    return [(value >> shift) & 1 for shift in range(width - 1, -1, -1)]


def bits_to_int(bits: Bits) -> int:
    """Собирает целое число из битовой последовательности.

    >>> bits_to_int([0, 0, 0, 0, 0, 1, 0, 1])
    5
    """
    value = 0
    for bit in bits:
        value = (value << 1) | (bit & 1)
    return value


def text_to_bits(text: str, encoding: str = "utf-8") -> Bits:
    """Переводит секретное сообщение в биты."""
    return bytes_to_bits(text.encode(encoding))


def bits_to_text(bits: Bits, encoding: str = "utf-8") -> str:
    """Собирает сообщение из битов.

    Повреждённая последовательность может не быть корректной строкой в
    заданной кодировке, поэтому непреобразуемые байты заменяются символом
    подстановки: приложение должно уметь показать пользователю частично
    восстановленный результат, а не аварийно завершиться.
    """
    return bits_to_bytes(bits).decode(encoding, errors="replace")


def hamming_distance(a: Bits, b: Bits) -> int:
    """Расстояние Хэмминга — число позиций, в которых биты различаются.

    Последовательности разной длины сравниваются по наименьшей длине,
    а разница длин целиком засчитывается как различие: при повреждении
    контейнера часть битов может быть попросту утрачена.
    """
    common = min(len(a), len(b))
    diff = sum(1 for i in range(common) if a[i] != b[i])
    return diff + abs(len(a) - len(b))
