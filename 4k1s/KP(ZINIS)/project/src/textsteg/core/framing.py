"""Кадрирование: заголовок, контрольная сумма и синхронизация.

Приёмник получает из стеготекста лишь поток бит и не располагает никакими
сведениями о встроенном сообщении. Служебная информация, необходимая для
декодирования, передаётся в заголовке, а границы блоков перемежителя
обозначаются синхромаркерами.

Зачем нужны синхромаркеры
-------------------------
Деперемежитель обязан знать, с какого бита начинается блок. Текстовые
воздействия порождают не только подстановки, но также вставки и удаления:
удаление одного слова убирает из потока два бита, и вся последующая
последовательность смещается. Отсчитывая блоки вслепую, приёмник разрезал
бы поток не по границам, и повреждение распространилось бы на весь остаток
сообщения.

Синхромаркер — известная приёмнику комбинация бит, размещаемая перед каждым
кадром. Приёмник не отсчитывает биты, а отыскивает маркер, тем самым заново
устанавливая границу кадра. Накопленное смещение обнуляется, и повреждение
локализуется в пределах одного кадра.

Почему заголовок не перемежается
--------------------------------
Чтобы разложить матрицу деперемежителя, необходимо знать глубину d, которая
хранится в заголовке, размещённом внутри этой же матрицы. Круг размыкается
передачей заголовка отдельно, без перемежения (что равносильно d = 1).
Помехоустойчивым кодом заголовок при этом защищается: его повреждение
влечёт потерю всего сообщения.

Структура потока
----------------
    [маркер][заголовок: код, без перемежения]
    [маркер][кадр 1][маркер][кадр 2]...[маркер][кадр M]

Размер кадра постоянен и не зависит от глубины перемежения; подробное
обоснование приведено в модуле pipeline.
"""

from __future__ import annotations

from dataclasses import dataclass

from ..errors import HeaderError
from .bits import Bits, bits_to_int, int_to_bits

# --------------------------------------------------------------------------
# Синхромаркер
# --------------------------------------------------------------------------

#: Длина синхромаркера в битах.
SYNC_MARKER_LENGTH = 16

#: Значение синхромаркера.
#:
#: Комбинация подобрана полным перебором 16-разрядных последовательностей по
#: трём критериям.
#:
#: 1. Равное число нулей и единиц (по восемь). Сбалансированная комбинация
#:    отличима от однородных участков потока, состоящих преимущественно из
#:    нулей или единиц.
#:
#: 2. Минимальный боковой лепесток апериодической автокорреляции. Для
#:    последовательности, записанной в форме +-1, величина
#:
#:        R(s) = sum_i a_i * a_(i+s),  s != 0,
#:
#:    у выбранной комбинации не превосходит по модулю 3. Это наименьшее
#:    достижимое значение среди всех сбалансированных 16-разрядных
#:    последовательностей: перебором установлено, что комбинаций с боковым
#:    лепестком 1 или 2 не существует.
#:
#: 3. Серии одинаковых бит не длиннее трёх.
#:
#: Практическое следствие второго свойства: при сдвигах, где перекрытие
#: составляет не менее половины длины маркера, число несовпадений не
#: опускается ниже четырёх, то есть вдвое превышает допуск поиска. Сдвинутая
#: копия маркера поэтому не опознаётся как маркер. При больших сдвигах
#: перекрытие мало, но такие позиции опасности не представляют: окно
#: сравнения заполняется в основном соседними битами полезной нагрузки.
SYNC_MARKER_VALUE = 0x15B3

#: Синхромаркер в виде битовой последовательности: 0001010110110011.
SYNC_MARKER: Bits = int_to_bits(SYNC_MARKER_VALUE, SYNC_MARKER_LENGTH)

#: Допустимое число несовпавших бит при поиске маркера. Сам маркер тоже
#: передаётся по повреждаемому каналу, поэтому поиск ведётся с допуском.
#:
#: Величина допуска — размен между двумя видами отказа.
#:
#: Завышенный допуск ведёт к ЛОЖНОЙ синхронизации: произвольный участок
#: потока совпадает с маркером с вероятностью
#:
#:     P(t) = (сумма C(16, i), i = 0..t) / 2^16,
#:
#: то есть 1,5e-5 при t = 0, 2,6e-4 при t = 1 и 2,1e-3 при t = 2. В окне
#: поиска шириной +-68 позиций (137 положений) ожидаемое число ложных
#: совпадений составляет 0,002, 0,036 и 0,29 соответственно. Значение t = 2
#: означало бы ложную синхронизацию примерно на каждом третьем разрушенном
#: кадре, причём приёмник принял бы случайные биты за данные, не сообщив об
#: утрате кадра.
#:
#: Заниженный допуск ведёт к ПРОПУСКУ настоящего маркера. При вероятности
#: ошибки в канале p доля маркеров с двумя и более ошибками составляет
#: примерно C(16,2) * p^2, то есть около 1,2 % при p = 0,01.
#:
#: Принято t = 1. Пропуск маркера приводит к честному отказу — кадр
#: помечается утраченным, и пользователь получает достоверное сообщение,
#: тогда как ложная синхронизация выдаёт мусор под видом данных.
MARKER_TOLERANCE = 1

# --------------------------------------------------------------------------
# Контрольная сумма CRC-16/CCITT-FALSE
# --------------------------------------------------------------------------

#: Порождающий полином x^16 + x^12 + x^5 + 1.
_CRC16_POLYNOMIAL = 0x1021
#: Начальное значение регистра.
_CRC16_INIT = 0xFFFF


def crc16(data: bytes) -> int:
    """Вычисляет контрольную сумму CRC-16/CCITT-FALSE.

    Реализация повторяет работу регистра сдвига с обратной связью: на каждом
    шаге старший бит регистра складывается по модулю 2 с очередным битом
    данных, регистр сдвигается влево, и при вытеснении единицы выполняется
    сложение с порождающим полиномом.

    Контрольная сумма позволяет приёмнику отличить верно восстановленное
    сообщение от повреждённого: код Хэмминга сообщает о состоянии отдельных
    блоков, но не о целостности сообщения в целом.
    """
    register = _CRC16_INIT
    for byte in data:
        register ^= byte << 8
        for _ in range(8):
            if register & 0x8000:
                register = ((register << 1) ^ _CRC16_POLYNOMIAL) & 0xFFFF
            else:
                register = (register << 1) & 0xFFFF
    return register


# --------------------------------------------------------------------------
# Заголовок
# --------------------------------------------------------------------------

#: Сигнатура формата (старшие 4 бита байта сигнатуры).
FORMAT_SIGNATURE = 0xA
#: Версия алгоритма (младшие 4 бита байта сигнатуры).
FORMAT_VERSION = 0x1

_SIGNATURE_BITS = 8
_LENGTH_BITS = 16
_DEPTH_BITS = 8
_CRC_BITS = 16

#: Полная длина заголовка: 8 + 16 + 8 + 16 = 48 бит (6 байт).
HEADER_BITS = _SIGNATURE_BITS + _LENGTH_BITS + _DEPTH_BITS + _CRC_BITS

#: Наибольшая длина сообщения, представимая полем длины.
MAX_MESSAGE_BYTES = (1 << _LENGTH_BITS) - 1


@dataclass(frozen=True)
class Header:
    """Служебные сведения, передаваемые перед сообщением.

    Поля:
        message_length — длина сообщения в байтах; указывает, где кончаются
            данные и начинается заполнение незанятых позиций контейнера;
        depth — глубина перемежения, с которой собран поток;
        checksum — CRC-16 исходного сообщения для проверки целостности.
    """

    message_length: int
    depth: int
    checksum: int

    def to_bits(self) -> Bits:
        """Сериализует заголовок в 48 бит."""
        if not 0 <= self.message_length <= MAX_MESSAGE_BYTES:
            raise HeaderError(
                f"длина сообщения должна быть от 0 до {MAX_MESSAGE_BYTES} байт"
            )
        if not 1 <= self.depth <= 255:
            raise HeaderError("глубина перемежения должна быть от 1 до 255")

        signature = (FORMAT_SIGNATURE << 4) | FORMAT_VERSION
        return (
            int_to_bits(signature, _SIGNATURE_BITS)
            + int_to_bits(self.message_length, _LENGTH_BITS)
            + int_to_bits(self.depth, _DEPTH_BITS)
            + int_to_bits(self.checksum, _CRC_BITS)
        )

    @classmethod
    def from_bits(cls, bits: Bits) -> Header:
        """Разбирает заголовок из 48 бит.

        Несовпадение сигнатуры означает, что в тексте нет сообщения нашего
        формата либо заголовок повреждён невосстановимо.
        """
        if len(bits) < HEADER_BITS:
            raise HeaderError(
                f"для заголовка требуется {HEADER_BITS} бит, получено {len(bits)}"
            )

        offset = 0
        signature = bits_to_int(bits[offset:offset + _SIGNATURE_BITS])
        offset += _SIGNATURE_BITS
        message_length = bits_to_int(bits[offset:offset + _LENGTH_BITS])
        offset += _LENGTH_BITS
        depth = bits_to_int(bits[offset:offset + _DEPTH_BITS])
        offset += _DEPTH_BITS
        checksum = bits_to_int(bits[offset:offset + _CRC_BITS])

        if (signature >> 4) != FORMAT_SIGNATURE:
            raise HeaderError("сигнатура формата не распознана")
        if (signature & 0x0F) != FORMAT_VERSION:
            raise HeaderError(
                f"версия алгоритма {signature & 0x0F} не поддерживается"
            )
        if depth < 1:
            raise HeaderError("недопустимая глубина перемежения")

        return cls(
            message_length=message_length, depth=depth, checksum=checksum
        )


# --------------------------------------------------------------------------
# Поиск синхромаркеров
# --------------------------------------------------------------------------

def marker_distance(bits: Bits, position: int) -> int:
    """Число несовпадений маркера с фрагментом потока в заданной позиции."""
    fragment = bits[position:position + SYNC_MARKER_LENGTH]
    if len(fragment) < SYNC_MARKER_LENGTH:
        return SYNC_MARKER_LENGTH
    return sum(1 for a, b in zip(fragment, SYNC_MARKER, strict=True) if a != b)


def find_marker(
    bits: Bits,
    expected: int,
    window: int,
    tolerance: int = MARKER_TOLERANCE,
) -> int | None:
    """Отыскивает синхромаркер вблизи ожидаемой позиции.

    Поиск ведётся не по всему потоку, а в окне вокруг ожидаемой позиции.
    Такое ограничение принципиально: случайная последовательность может
    совпасть с маркером, и глобальный поиск давал бы ложные срабатывания.
    Ширина окна задаёт допустимое накопленное смещение, вызванное вставками
    и удалениями символов в контейнере.

    Возвращает позицию первого бита маркера либо None, если в окне маркер
    не найден. При нескольких подходящих позициях предпочтение отдаётся
    ближайшей к ожидаемой, а при равном удалении — той, где несовпадений
    меньше.

    Порядок приоритетов существен. Полезная нагрузка способна случайно
    воспроизвести комбинацию маркера точно, тогда как настоящий маркер,
    прошедший по повреждаемому каналу, может содержать одно-два несовпадения.
    Если бы решающей была величина несовпадений, точный двойник в глубине
    окна побеждал бы слегка повреждённый настоящий маркер рядом с ожидаемой
    позицией, и приёмник синхронизировался бы по ложной границе. Ожидаемая
    позиция известна с точностью до накопленного смещения и служит более
    надёжным признаком, чем число совпавших бит.
    """
    low = max(0, expected - window)
    high = min(len(bits) - SYNC_MARKER_LENGTH, expected + window)

    best_position: int | None = None
    best_key: tuple[int, int] | None = None

    for position in range(low, high + 1):
        distance = marker_distance(bits, position)
        if distance > tolerance:
            continue
        key = (abs(position - expected), distance)
        if best_key is None or key < best_key:
            best_position = position
            best_key = key

    return best_position
